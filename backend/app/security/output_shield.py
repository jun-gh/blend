"""Output Policy Shield with System Prompt Leak Prevention and Safe De-anonymization."""

from __future__ import annotations

import logging
import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from app.security.pii_scrubber import SafeTokenMap

log = logging.getLogger(__name__)

# Phrases that indicate leaking of the internal system instructions
_SYSTEM_PROMPT_LEAK_SIGNATURES = [
    re.compile(r"(?i)you\s+are\s+blend,\s+an\s+intelligent\s+research\s+assistant"),
    re.compile(r"(?i)answer\s+only\s+using\s+information\s+found\s+in\s+the\s+context\s+below"),
    re.compile(r"(?i)if\s+the\s+context\s+does\s+not\s+contain\s+enough\s+information,\s+state\s+that\s+clearly"),
    re.compile(r"(?i)cite\s+your\s+sources\s+using\s+\[doc:\s+<title>\]"),
    re.compile(r"(?i)system\s+instruction\s*:\s*you\s+are"),
    re.compile(r"(?i)<user_ticket_content>.*?</user_ticket_content>", re.DOTALL),
]


def check_system_prompt_leak(answer: str) -> bool:
    """Return True if model output appears to leak internal system instructions."""
    if not answer:
        return False
    return any(pat.search(answer) for pat in _SYSTEM_PROMPT_LEAK_SIGNATURES)


def shield_output(
    answer: str,
    token_map: SafeTokenMap | None = None,
    allow_deanonymization: bool = True,
    allowed_categories: set[str] | None = None,
) -> str:
    """Apply output safety policy, preventing prompt leaks and managing de-anonymization.

    Args:
        answer: Raw response generated by the LLM.
        token_map: Optional SafeTokenMap populated during query or document processing.
        allow_deanonymization: If True, restores permitted categories (e.g. EMAIL, PHONE).
        allowed_categories: Categories allowed for restoration. Defaults to safe non-secrets.
    """
    if not answer:
        return answer

    # 1. System Prompt Leak Prevention
    if check_system_prompt_leak(answer):
        log.warning("Output Policy Shield detected system prompt leakage. Sanitizing response.")
        # Neutralize any leaked system rules
        sanitized_answer = (
            "I am Blend, your hybrid search research assistant. "
            "I provide grounded answers strictly based on your documents."
        )
        return sanitized_answer

    # 2. Safe De-anonymization
    if token_map and allow_deanonymization and token_map.has_redactions:
        # High-risk credentials (API keys, passwords, credit cards, SSNs) are NEVER restored!
        safe_categories = allowed_categories or {"EMAIL", "PHONE"}
        answer = token_map.restore(answer, allowed_categories=safe_categories)

    return answer
